import pytest

from app.services.chat.policies import direct_intent, requests_support_form


@pytest.mark.parametrize("message", [
    "оставить заявку",
    "Хочу оставить заявку.",
    "Оформи, пожалуйста, заявку в ТП",
    "оформить обращение",
    "Создай заявку по этой проблеме",
    "Давайте заведем тикет",
    "Мне нужно обращение в поддержку",
    "Можно написать в техническую поддержку?",
    "Напиши письмо в ТП",
    "хочу связаться с техподдержкой",
    "подать заявку",
    "Заявку оставь, пожалуйста",
    "Не работает принтер. Хочу оставить заявку",
    "Не могу настроить сканер, хочу оставить заявку в ТП",
    "Не получается оформить заказ, поэтому хочу написать в техподдержку",
    "Не хочу продолжать настройку, а хочу оформить заявку",
    "Хочу оставить заявку по ошибке «не печатает»",
    "отправить заявку в техподдержку",
    "ОСТАВИТЬ ЗАЯВКУ!",
])
def test_support_form_request_is_understood_without_operator_keyword(message):
    assert requests_support_form(message)
    assert direct_intent(message) == "HUMAN"


@pytest.mark.parametrize("message", [
    "не хочу оставлять заявку",
    "не надо оформлять заявку",
    "не оставлять заявку",
    "Заявку оставлять не надо",
    "оставить заявку не хочу",
    "не отправляй заявку, помоги сам",
    "Я уже оставил заявку",
    "Посмотреть статус заявки",
    "Отмена заявки",
    "Продолжить с ботом",
    "Напиши письмо маме",
    "Что означает слово «оставить заявку»?",
    "Бот не реагирует на фразу «оставить заявку»",
    "Не хочу писать в поддержку",
    "Письмо в поддержку не нужно",
    "ненадо оставлять заявку",
    "Нехочу оформлять заявку",
    "Если не поможет, оставлю заявку",
    "Когда перестанет работать, надо оформить заявку",
    "Если потребуется написать письмо в поддержку",
    "Заявку не хочу оставлять",
    "Заявку не надо оформлять",
    "оформить не заявку, а решить проблему",
    "Не надо мне оставлять заявку",
    "Не хочу больше оставлять заявку",
    "Не могу создать заявку в 1С",
    "Не получается оформить заявку покупателю",
    "Пользователь не может создать заявку",
    "У меня не удается отправить заявку",
    "Заявку не могу создать",
    "Создать заявку не получается",
    "Не смог оформить заявку покупателю",
    "настроить сканер",
])
def test_support_form_request_does_not_override_negation_or_other_messages(message):
    assert not requests_support_form(message)
    assert direct_intent(message) is None


@pytest.mark.parametrize("message", ["оператор", "специалист", "позвать специалиста"])
def test_operator_keeps_the_existing_human_choice_intent(message):
    assert direct_intent(message) == "HUMAN"
    assert not requests_support_form(message)


@pytest.mark.parametrize("message", ["помогло", "не помогло"])
def test_feedback_keeps_the_existing_intent(message):
    assert direct_intent(message) == "FEEDBACK"
