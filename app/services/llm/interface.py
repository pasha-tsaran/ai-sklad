from typing import Protocol

from app.schemas.contracts import AnalysisResult, AnswerResult, DialogueResult, FollowupResult, SummaryResult
from app.services.rag.interface import Candidate


class LanguageModel(Protocol):
    name: str

    def analyze(self, message: str) -> AnalysisResult: ...
    def dialogue(self, message: str, context: dict) -> DialogueResult: ...
    def analyze_context(self, message: str, context: dict) -> AnalysisResult: ...
    def followup(self, question: str, context: dict, approved_source: dict) -> FollowupResult: ...
    def compose(self, candidate: Candidate) -> AnswerResult: ...
    def summarize(self, transcript: str) -> SummaryResult: ...
